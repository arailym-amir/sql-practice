/*Data: two fictional tables, see below:

books table
orders table

Task: You are working with an online bookstore database that contains the above two tables. Write a query that would return the total revenue generated by each book.

Expected Output: The result of the query would include the book title (title) and total 
revenue (total_revenue), sorted in descending order of revenue.*/

select 
  b.title, 
  sum(o.quantity * b.price) as total_revenue

from 
  books b
  inner join orders o on b.book_id = o.book_id

group by 
  b.title

order by 
  total_revenue desc;
